#!/usr/bin/env python3
"""Refresh three same-source lists with explicit Shadowrocket regex approximations."""

import argparse
import fnmatch
import os
import re
import tempfile
from pathlib import Path
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
NAMES = ("category-ai-!cn", "netflix", "google")
POLICIES = ("AI", "Netflix", "Google")
BASE = "https://raw.githubusercontent.com/MetaCubeX/meta-rules-dat/meta/geo/geosite/classical/"
CHATGPT = r"^chatgpt-async-webps-prod-\S+-\d+\.webpubsub\.azure\.com$"
REGEX_MAP = {CHATGPT: ["chatgpt-async-webps-prod-*-*.webpubsub.azure.com"]}
for prefix in ("apiproxy-device-prod-nlb-", "apiproxy-website-nlb-prod-",
               "dualstack.apiproxy-", "dualstack.ichnaea-web-"):
    pattern = r"(^|\.)" + re.escape(prefix) + r".+\.amazonaws\.com$"
    # re.escape escapes hyphens even though the upstream expression does not.
    pattern = pattern.replace(r"\-", "-")
    host = prefix + "*.amazonaws.com"
    REGEX_MAP[pattern] = [host, "*." + host]
for suffix in ("xn--ngstr-lra8j.com", "googlevideo.com"):
    pattern = (r"^r+[0-9]+(---|\.)sn-(2x3|ni5|j5o)\w{5}\."
               + re.escape(suffix).replace(r"\-", "-") + "$"
               )
    REGEX_MAP[pattern] = [f"r*{sep}sn-{region}?????.{suffix}"
                          for sep in ("---", ".") for region in ("2x3", "ni5", "j5o")]


def convert(text, name):
    output = [f"# Source: {BASE}{name}.list",
              "# Generated by scripts/update_compat.py; do not edit manually.",
              "# shortcut: wildcard compatibility matches slightly more than the original regex;",
              "# replace it when Shadowrocket DOMAIN-REGEX support is verified."]
    replaced = 0
    for row in text.splitlines():
        row = row.strip()
        if not row or row.startswith("#"):
            continue
        fields = row.split(",")
        if len(fields) != 2:
            raise ValueError(f"Unexpected policy/options in {name}: {row}")
        kind, value = fields
        if kind == "DOMAIN-REGEX":
            if value not in REGEX_MAP:
                raise ValueError(f"Unknown upstream regex in {name}: {value}")
            output.append(f"# Original DOMAIN-REGEX: {value}")
            output.extend(f"DOMAIN-WILDCARD,{host}" for host in REGEX_MAP[value])
            replaced += 1
        elif kind in {"DOMAIN", "DOMAIN-SUFFIX", "DOMAIN-KEYWORD"} and re.fullmatch(r"[A-Za-z0-9_.-]+", value):
            output.append(row)
        else:
            raise ValueError(f"Unsupported rule in {name}: {row}")
    if len(output) == 4:
        raise ValueError(f"Empty upstream list: {name}")
    return "\n".join(output) + "\n", replaced


def self_check():
    assert len(REGEX_MAP) == 7
    for pattern, hosts in REGEX_MAP.items():
        sample = ("chatgpt-async-webps-prod-test-123.webpubsub.azure.com" if pattern == CHATGPT
                  else hosts[0].replace("r*", "rr12").replace("*", "test").replace("?", "a"))
        assert re.search(pattern, sample), (pattern, sample)
        assert any(fnmatch.fnmatchcase(sample, host) for host in hosts), sample
        assert not any(fnmatch.fnmatchcase(sample + ".evil.example", host) for host in hosts)
        assert not any(fnmatch.fnmatchcase("unrelated.example.com", host) for host in hosts)
        converted, count = convert("DOMAIN-REGEX," + pattern, "self-check")
        assert count == 1 and converted.count("DOMAIN-WILDCARD,") == len(hosts)
    for invalid in ("DOMAIN-REGEX,^unknown$", "DOMAIN,example.com,PROXY", "IP-CIDR,1.1.1.1/32", "DOMAIN,", ""):
        try:
            convert(invalid, "self-check")
        except ValueError:
            pass
        else:
            raise AssertionError(f"Accepted unexpected upstream content: {invalid}")


def inline(config, contents):
    for name, policy in zip(NAMES, POLICIES):
        begin = f"# BEGIN COMPAT {name} {policy}\n"
        end = f"# END COMPAT {name}\n"
        if config.count(begin) != 1 or config.count(end) != 1:
            raise ValueError(f"Missing or duplicate compatibility markers: {name}")
        before, block = config.split(begin)
        if end not in block:
            raise ValueError(f"Misordered compatibility markers: {name}")
        previous, after = block.split(end)
        if "# BEGIN COMPAT " in previous or "# END COMPAT " in previous:
            raise ValueError(f"Nested compatibility markers: {name}")
        rows = [row if not row or row.startswith("#") else f"{row},{policy}"
                for row in contents[name].splitlines()]
        config = before + begin + "\n".join(rows) + "\n" + end + after
    return config


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check conversions and inline consistency offline")
    args = parser.parse_args()
    self_check()
    destination = ROOT / "rules" / "compat"
    config_path = ROOT / "shadowrocket.conf"
    config = config_path.read_text(encoding="utf-8")
    if args.check:
        contents = {name: (destination / (name + ".list")).read_text(encoding="utf-8") for name in NAMES}
        if inline(config, contents) != config:
            raise ValueError("Compatibility lists differ from inline configuration; run this script to refresh")
        print("PASS: 7 regex mappings, domain boundaries, invalid inputs, and 3 inline blocks")
        return
    results = {}
    for name in NAMES:
        with urlopen(BASE + name + ".list", timeout=30) as response:
            results[name] = convert(response.read().decode("utf-8-sig"), name)
    contents = {name: content for name, (content, _) in results.items()}
    files = {destination / (name + ".list"): content for name, content in contents.items()}
    files[config_path] = inline(config, contents)
    destination.mkdir(parents=True, exist_ok=True)
    # Stage and validate everything before replacing any list or configuration.
    with tempfile.TemporaryDirectory(dir=destination) as temporary:
        for path, content in files.items():
            (Path(temporary) / path.name).write_text(content, encoding="utf-8")
        if config_path.read_text(encoding="utf-8") != config:
            raise ValueError("Configuration changed during download; retry without concurrent edits")
        for path in files:
            os.replace(Path(temporary) / path.name, path)
        for name, (content, count) in results.items():
            rules = sum(not row.startswith("#") for row in content.splitlines())
            print(f"{name}: {rules} rules; {count} regex rules adapted")


if __name__ == "__main__":
    main()
